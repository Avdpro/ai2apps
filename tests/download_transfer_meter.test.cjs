const fs = require('node:fs');
const vm = require('node:vm');
const assert = require('node:assert/strict');
const context = { window: {} };
vm.runInNewContext(fs.readFileSync('ai2apps/web/static/js/capability_provisioning.js', 'utf8'), context);
const meter = context.window.AI2AppsCapabilities.createTransferMeter();
assert.equal(meter('resumed', 1024, 4096, 0), '— · ETA —');
assert.equal(meter('resumed', 2048, 4096, 1000), '1.0 KB/s · ETA 00:00:02');
for (let time = 2000; time <= 6000; time += 1000) meter('resumed', 2048, 4096, time);
assert.equal(meter('resumed', 2048, 4096, 7000), '0 B/s · ETA —');
assert.equal(meter('resumed', 1024, 4096, 8000), '— · ETA —');
assert.equal(meter('next', 2048, 4096, 9000), '— · ETA —');
assert.equal(meter('next', 4096, 4096, 10000), '2.0 KB/s · ETA —');
console.log('Download transfer meter checks passed');
const format = context.window.AI2AppsCapabilities.formatDownloadProgress;
const telemetry = { bytesCompleted: 1024, bytesTotal: 4096, bytesPerSecond: 1024, etaSeconds: 3, sampledAt: 10 };
assert.equal(format(telemetry, true, 11000), '下载速度 1.0 KB/s · ETA 00:00:03');
assert.equal(format(telemetry, true, 16000), '下载速度 0 B/s · ETA —');
assert.equal(format(telemetry, false, 16000), '最近下载：1.0 KB / 4.0 KB · 最近速度 1.0 KB/s');
assert.equal(format({...telemetry, bytesPerSecond: null, etaSeconds: null}, true, 11000), '下载速度 — · ETA —');
